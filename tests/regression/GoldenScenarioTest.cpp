/// T4's golden regression: a fixed farm, a fixed weather year and a fixed seed,
/// compared point by point against a series committed to the repository.
///
/// **What this catches that nothing else does.** The conservation suite proves
/// the books balance and the validation suite proves the seasonal shape is
/// right, and a change can pass both while quietly moving every number. This
/// suite has no opinion about whether the model is correct - it only says
/// whether it still answers what it answered yesterday, so an unintended change
/// arrives as a failed test rather than as a different figure in a report six
/// months later.
///
/// **The baseline is never regenerated by the thing it judges.** A test that
/// writes its own expectations when they do not match is a test that always
/// passes. Rewriting it takes a deliberate act - `PADDOCK_WRITE_GOLDEN_BASELINE`
/// in the environment - and the diff is then reviewed like any other change,
/// because that diff *is* the record of what the model now says differently.

#include <gtest/gtest.h>

#include <algorithm>
#include <cmath>
#include <cstdlib>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>

